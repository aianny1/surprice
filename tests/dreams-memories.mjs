/** Dreams: scroll lights wishes one by one. Memories: scroll lifts each photo up and back. */
import { chromium } from 'playwright-core';
const BASE = process.env.BASE_URL ?? 'http://localhost:3100';
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const b = await chromium.launch({ channel: 'chrome', headless: true, args: ['--ignore-gpu-blocklist', '--enable-gpu', '--use-angle=d3d11'] });
const page = await b.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
const hop = async () => { await page.mouse.wheel(0, 220); await sleep(1400); };
await page.goto(`${BASE}/dreams?preview=1`);
await sleep(7000);
await page.screenshot({ path: 'tests/screens/dm-dreams-0.png' });
await hop(); await sleep(800);
await page.screenshot({ path: 'tests/screens/dm-dreams-1.png' });
await hop(); await sleep(800);
await page.screenshot({ path: 'tests/screens/dm-dreams-2.png' });
await hop(); await sleep(1200);
await page.screenshot({ path: 'tests/screens/dm-dreams-3.png' });
await hop(); await sleep(2500);
await page.screenshot({ path: 'tests/screens/dm-dreams-4.png' });
console.log('music hint shown:', !!(await page.$('[data-testid="music-hint"]')));
await page.goto(`${BASE}/memories?preview=1`);
await sleep(7000);
await hop(); await sleep(600);
await page.screenshot({ path: 'tests/screens/dm-mem-1.png' });
await hop(); await sleep(300);
await page.screenshot({ path: 'tests/screens/dm-mem-swap.png' });
console.log('focus visible:', !!(await page.$('[data-testid="memory-focus"]')));
console.log(errors.length ? 'ERRORS ' + [...new Set(errors)].join(' | ') : 'NO ERRORS');
await b.close();
